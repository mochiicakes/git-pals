/* Bundles assets/*.png into src/assets.ts */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { sep } from 'node:path';
import { PNG } from 'pngjs';

const lines: string[] = [];
for (const file of readdirSync('assets', { recursive: true }) as string[]) {
  if (!file.endsWith('.png')) continue;
  const name = file
    .split(sep)
    .join('/')
    .replace(/\.png$/, '');
  const bytes = readFileSync(`assets/${file}`);

  /* Pixel art only: no half-transparent pixels */
  const { data } = PNG.sync.read(bytes);
  for (let i = 3; i < data.length; i += 4) {
    if (data[i] !== 0 && data[i] !== 255) throw new Error(`${file}: has anti-aliased pixels`);
  }
  lines.push(`  '${name}': '${bytes.toString('base64')}',`);
}

lines.sort();
writeFileSync(
  'src/assets.ts',
  `/* Generated by npm run assets */\nexport const ASSETS: Record<string, string> = {\n${lines.join('\n')}\n};\n`,
);
console.log(`Bundled ${lines.length} images`);
